"""Generate a self-contained Kaggle script kernel that runs feature dumps.

The kernel embeds this repo's source, writes it to disk on Kaggle, runs
``scripts/dump_features.py`` once per model (each in its own process, so GPU
memory is fully released between checkpoints), and prints a sanity report.

    python scripts/make_kernel.py --model deepseek-ai/DeepSeek-R1-0528-Qwen3-8B --limit 20
    python scripts/make_kernel.py --model Qwen/Qwen3.5-4B --model allenai/Olmo-3-7B-Think \
        --problems-of deepseek-ai/DeepSeek-R1-0528-Qwen3-8B
    kaggle kernels push -p kaggle/aimo-selfperturb-dump --accelerator NvidiaTeslaT4 -t 3600

Kaggle's T4 option is a pair of cards (32 GB total), enough for an 8B model in
fp16 split across both with device_map="auto".
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EMBEDDED = [
    "src/selfperturb/__init__.py",
    "src/selfperturb/perturbations.py",
    "src/selfperturb/features.py",
    "scripts/dump_features.py",
]
SLUG = "aimo-selfperturb-dump"

RUNNER = '''\
"""Generated by scripts/make_kernel.py -- edit the generator, not this file."""
import json, shutil, subprocess, sys, time
from pathlib import Path

MODELS = {models!r}
LIMIT = {limit}
PROBLEMS_OF = {problems_of!r}
FILES = json.loads({files!r})

work = Path("/kaggle/working/repo")
for relative, content in FILES.items():
    target = work / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")

# Mirror the evaluation container's library versions.
subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                "transformers==5.13.0", "accelerate==1.13.0"], check=False)
import torch, transformers
print("torch", torch.__version__, "| transformers", transformers.__version__, flush=True)
print("gpus:", [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())], flush=True)

out = Path("/kaggle/working/features")
timings = {{}}
for model in MODELS:
    started = time.time()
    command = [sys.executable, str(work / "scripts/dump_features.py"),
               "--model", model, "--out", str(out), "--flush-every", "10"]
    if LIMIT:
        command += ["--limit", str(LIMIT)]
    if PROBLEMS_OF:
        command += ["--problems-of", PROBLEMS_OF]
    result = subprocess.run(command, cwd=work)
    timings[model] = {{"seconds": round(time.time() - started, 1), "returncode": result.returncode}}
    # Checkpoints total ~50 GB; clear each before the next download.
    shutil.rmtree(Path.home() / ".cache" / "huggingface" / "hub", ignore_errors=True)

import numpy as np
report = {{"timings": timings, "dumps": {{}}}}
for dump in sorted(out.glob("*.npz")):
    data = np.load(dump, allow_pickle=True)
    features, labels, columns = data["features"], data["labels"], list(data["columns"])
    entry = {{
        "cases": int(len(features)),
        "nan_or_inf": int((~np.isfinite(features)).sum()),
        "labels_from": str(data["labels_from"]) if "labels_from" in data.files else str(data["model_id"]),
    }}
    for name in ("distract_cos_d0.25", "distract_norm_d0.25", "base_entropy"):
        column = features[:, columns.index(name)]
        entry[name] = {{"mean": round(float(column.mean()), 4), "std": round(float(column.std()), 4)}}
    report["dumps"][str(data["model_id"])] = entry
print(json.dumps(report, indent=2))
Path("/kaggle/working/dump_report.json").write_text(json.dumps(report, indent=2))
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", action="append", required=True, help="repeatable")
    parser.add_argument("--limit", type=int, default=0, help="0 means every labelled case")
    parser.add_argument("--problems-of", default="", help="see dump_features.py --problems-of")
    parser.add_argument("--user", default="rajtaware10")
    arguments = parser.parse_args()

    files = {path: (ROOT / path).read_text(encoding="utf-8") for path in EMBEDDED}
    folder = ROOT / "kaggle" / SLUG
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "run.py").write_text(
        RUNNER.format(
            models=arguments.model,
            limit=arguments.limit,
            problems_of=arguments.problems_of,
            files=json.dumps(files),
        ),
        encoding="utf-8",
    )
    metadata = {
        "id": f"{arguments.user}/{SLUG}",
        "title": SLUG,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "kernel_sources": [],
        "competition_sources": [],
        "model_sources": [],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"wrote {folder} for {len(arguments.model)} model(s)")


if __name__ == "__main__":
    main()
