"""Generate a self-contained Kaggle script kernel that runs a feature dump.

The kernel embeds this repo's source, writes it to disk on Kaggle, runs
``scripts/dump_features.py``, and prints a sanity report. Push it with:

    python scripts/make_kernel.py --model deepseek-ai/DeepSeek-R1-0528-Qwen3-8B --limit 20
    kaggle kernels push -p kaggle/aimo-selfperturb-dump --accelerator NvidiaTeslaT4 -t 3600

Kaggle's T4 option is a pair of cards (32 GB total), enough for an 8B model in
fp16 split across both with device_map="auto".
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EMBEDDED = [
    "src/selfperturb/__init__.py",
    "src/selfperturb/perturbations.py",
    "src/selfperturb/features.py",
    "scripts/dump_features.py",
]
SLUG = "aimo-selfperturb-dump"

RUNNER = '''\
"""Generated by scripts/make_kernel.py -- edit the generator, not this file."""
import json, subprocess, sys, time
from pathlib import Path

MODEL = {model!r}
LIMIT = {limit}
FILES = json.loads({files!r})

work = Path("/kaggle/working/repo")
for relative, content in FILES.items():
    target = work / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")

import torch, transformers
print("torch", torch.__version__, "| transformers", transformers.__version__, flush=True)
print("gpus:", [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())], flush=True)
major, minor = (int(part) for part in transformers.__version__.split(".")[:2])
if (major, minor) < (4, 51):  # Qwen3 architecture support landed in 4.51
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-U", "transformers", "accelerate"], check=True)
    print("upgraded transformers; the dump subprocess picks up the new version", flush=True)

started = time.time()
command = [sys.executable, str(work / "scripts/dump_features.py"),
           "--model", MODEL, "--out", "/kaggle/working/features", "--flush-every", "5"]
if LIMIT:
    command += ["--limit", str(LIMIT)]
subprocess.run(command, check=True, cwd=work)
elapsed = time.time() - started

import numpy as np
dump = next(Path("/kaggle/working/features").glob("*.npz"))
data = np.load(dump, allow_pickle=True)
features, labels, columns = data["features"], data["labels"], list(data["columns"])
report = {{
    "model": MODEL,
    "cases": int(len(features)),
    "n_features": int(features.shape[1]),
    "nan_or_inf": int((~np.isfinite(features)).sum()),
    "robust_fraction": float(labels.mean()),
    "wall_seconds_total": round(elapsed, 1),
}}
# Per perturbation: how often it applied, and mid-depth drift where it did.
# Robust vs spurious drift is the signal the whole method rests on.
for name in ("rename", "numerals", "typos", "distract", "rephrase", "number_jitter"):
    applied = features[:, columns.index(f"{{name}}_applied")] > 0.5
    cosine = features[:, columns.index(f"{{name}}_cos_d0.5")]
    entry = {{"applied": int(applied.sum())}}
    for label, mask in (("robust", applied & labels), ("spurious", applied & ~labels)):
        if mask.any():
            entry[f"cos_mid_{{label}}"] = round(float(cosine[mask].mean()), 4)
    report[name] = entry
for name in ("base_entropy", "base_top1", "base_margin"):
    column = features[:, columns.index(name)]
    report[name] = {{"robust": round(float(column[labels].mean()), 4),
                    "spurious": round(float(column[~labels].mean()), 4)}}
print(json.dumps(report, indent=2))
Path("/kaggle/working/smoke_report.json").write_text(json.dumps(report, indent=2))
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", required=True)
    parser.add_argument("--limit", type=int, default=0, help="0 means every labelled case")
    parser.add_argument("--user", default="rajtaware10")
    arguments = parser.parse_args()

    files = {path: (ROOT / path).read_text(encoding="utf-8") for path in EMBEDDED}
    folder = ROOT / "kaggle" / SLUG
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "run.py").write_text(
        RUNNER.format(model=arguments.model, limit=arguments.limit, files=json.dumps(files)),
        encoding="utf-8",
    )
    metadata = {
        "id": f"{arguments.user}/{SLUG}",
        "title": SLUG,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "kernel_sources": [],
        "competition_sources": [],
        "model_sources": [],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"wrote {folder}")


if __name__ == "__main__":
    main()
