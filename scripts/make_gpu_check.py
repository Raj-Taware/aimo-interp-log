"""Generate a Kaggle kernel that runs the exact submission ZIP on all four models.

The bundle swallows exceptions by design -- a failed load silently predicts
the fallback for every case and still scores as "valid". This kernel calls the
same code path but surfaces what the bundle hides: whether each model loaded,
whether predictions came from the probe or the fallback, per-case latency, and
whether two runs agree exactly (Codabench requires determinism).

    python scripts/build_bundle.py
    python scripts/make_gpu_check.py
    kaggle kernels push -p kaggle/aimo-selfperturb-gpu-check --accelerator NvidiaTeslaT4 -t 3600
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUNDLE = ROOT / "dist" / "solution-self-perturb-small.zip"
SLUG = "aimo-selfperturb-gpu-check"
SMALL_MODELS = [
    "Qwen/Qwen3.5-4B",
    "Skywork/Skywork-OR1-Math-7B",
    "allenai/Olmo-3-7B-Think",
    "deepseek-ai/DeepSeek-R1-0528-Qwen3-8B",
]

RUNNER = '''\
"""Generated by scripts/make_gpu_check.py -- edit the generator, not this file."""
import base64, io, json, os, shutil, subprocess, sys, time, traceback, zipfile
from pathlib import Path

MODELS = {models!r}
PROBLEMS = {problems!r}
BUNDLE_B64 = {bundle!r}

# Mirror the evaluation container's library versions.
subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                "transformers==5.13.0", "accelerate==1.13.0"], check=False)

bundle_dir = Path("/kaggle/working/bundle")
zipfile.ZipFile(io.BytesIO(base64.b64decode(BUNDLE_B64))).extractall(bundle_dir)
sys.path.insert(0, str(bundle_dir))

import torch, transformers
print("torch", torch.__version__, "| transformers", transformers.__version__, flush=True)
print("gpus:", [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())], flush=True)

import solution
from selfperturb.features import case_features, load_model
import selfperturb_infer

report = {{"transformers": transformers.__version__, "models": {{}}}}
for model_id in MODELS:
    entry = {{}}
    print(f"\\n===== {{model_id}}", flush=True)
    try:
        # 1. Load directly, so a failure is visible instead of swallowed.
        started = time.time()
        tokenizer, model = load_model(model_id)
        entry["load_seconds"] = round(time.time() - started, 1)
        entry["n_hidden_states"] = model.config.num_hidden_layers + 1
        # 2. Features directly, so shape problems surface.
        started = time.time()
        vector = case_features(tokenizer, model, PROBLEMS[0])
        entry["feature_dim"] = int(vector.shape[0])
        entry["seconds_per_case"] = round(time.time() - started, 2)
        entry["features_finite"] = bool(__import__("numpy").isfinite(vector).all())
        del model; __import__("gc").collect(); torch.cuda.empty_cache()
        # 3. The exact submission entry point, twice, for determinism.
        started = time.time()
        first = solution.are_robust(model_id, PROBLEMS)
        entry["are_robust_seconds"] = round(time.time() - started, 1)
        second = solution.are_robust(model_id, PROBLEMS)
        entry["predictions"] = first
        entry["deterministic"] = first == second
        entry["all_bool"] = all(type(p) is bool for p in first)
        entry["status"] = "ok"
    except Exception as error:
        entry["status"] = "error"
        entry["error"] = f"{{type(error).__name__}}: {{error}}"
        traceback.print_exc()
    # Memory still held after the bundle's own cleanup means the bundle leaks.
    __import__("gc").collect()
    entry["gpu_mb_after"] = [round(torch.cuda.memory_allocated(i) / 2**20) for i in range(torch.cuda.device_count())]
    report["models"][model_id] = entry
    print(json.dumps(entry, indent=2), flush=True)
    # Four checkpoints total ~50 GB; clear each before the next download.
    torch.cuda.empty_cache()
    shutil.rmtree(Path.home() / ".cache" / "huggingface" / "hub", ignore_errors=True)

Path("/kaggle/working/gpu_check.json").write_text(json.dumps(report, indent=2))
print("\\n" + json.dumps(report, indent=2))
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--user", default="rajtaware10")
    parser.add_argument("--n-problems", type=int, default=4)
    arguments = parser.parse_args()

    import pandas as pd

    frame = pd.read_parquet(ROOT / "data" / "raw" / "augmented-sample-math-agg.parquet")
    # Two robust and two spurious DeepSeek cases, so both decision paths run.
    robust = frame[frame["model_is_robust"]]["original_problem"].head(arguments.n_problems // 2)
    spurious = frame[~frame["model_is_robust"]]["original_problem"].head(arguments.n_problems // 2)
    problems = [str(p) for p in list(robust) + list(spurious)]

    folder = ROOT / "kaggle" / SLUG
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "run.py").write_text(
        RUNNER.format(
            models=SMALL_MODELS,
            problems=problems,
            bundle=base64.b64encode(BUNDLE.read_bytes()).decode("ascii"),
        ),
        encoding="utf-8",
    )
    metadata = {
        "id": f"{arguments.user}/{SLUG}",
        "title": SLUG,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "kernel_sources": [],
        "competition_sources": [],
        "model_sources": [],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"wrote {folder} ({len(problems)} problems x {len(SMALL_MODELS)} models)")


if __name__ == "__main__":
    main()
