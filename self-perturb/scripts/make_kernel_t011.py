"""T-011: generate the self-contained Kaggle kernel (canary, then v4 ZIP per model).

    python scripts/make_kernel_t011.py --out kaggle/aimo-t011-v4check
    kaggle kernels push -p kaggle/aimo-t011-v4check --accelerator NvidiaTeslaT4

Order: DeepSeek first (PROTOCOL canary, then v4 ZIP), then the other three
models (v4 ZIP). Same runner as T-010 (zip_predict.py). Each step is its own process; the HF cache
is cleared between models. Embeds no secrets -- every checkpoint is public.
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
TEXT = ["src/selfperturb/__init__.py", "src/selfperturb/perturbations.py", "src/selfperturb/features.py",
        "scripts/zip_predict.py", "scripts/canary.py"]
BINARY = {
    "zips/v4.zip": ROOT / "results/submissions/solution-self-perturb-small-v4.zip",
    "ref/deepseek_t008.npz": ROOT / "results/grok/T-008/dumps/deepseek-ai_DeepSeek-R1-0528-Qwen3-8B.npz",
    "data/rows.json": ROOT / "results/grok/T-010/trainv2_small_rows.json",
    "data/canary.jsonl": REPO / "collab/canary.jsonl",
}
MODELS = ["deepseek-ai/DeepSeek-R1-0528-Qwen3-8B", "Qwen/Qwen3.5-4B",
          "Skywork/Skywork-OR1-Math-7B", "allenai/Olmo-3-7B-Think"]

RUNNER = '''\
"""Generated by scripts/make_kernel_t011.py -- edit the generator, not this file."""
import base64, json, re, shutil, subprocess, sys, time, zipfile
from pathlib import Path

MODELS = {models!r}
TEXT = json.loads({text!r})
BINARY = json.loads({binary!r})

work = Path("/kaggle/working/repo")
for rel, content in TEXT.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(content, encoding="utf-8")
for rel, blob in BINARY.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_bytes(base64.b64decode(blob))
for name in ("v4",):
    with zipfile.ZipFile(work / f"zips/{{name}}.zip") as z:
        z.extractall(work / f"zips/{{name}}")

subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                "transformers==5.13.0", "accelerate==1.13.0"], check=False)
import torch, transformers, accelerate
env = {{"torch": torch.__version__, "cuda": torch.version.cuda, "transformers": transformers.__version__,
        "accelerate": accelerate.__version__,
        "gpus": [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]}}
print("ENV", json.dumps(env), flush=True)

out = Path("/kaggle/working/T-011")
(out / "preds").mkdir(parents=True, exist_ok=True)
safe = lambda m: re.sub(r"[^A-Za-z0-9._-]+", "_", m).strip("_")
timings = {{}}

def step(key, cmd):
    t0 = time.time()
    print("STEP", key, flush=True)
    r = subprocess.run(cmd, cwd=work)
    timings[key] = {{"seconds": round(time.time() - t0, 1), "returncode": r.returncode}}
    print("DONE", key, json.dumps(timings[key]), flush=True)

py = sys.executable
for model in MODELS:
    if model.startswith("deepseek-ai/"):
        step("canary", [py, "scripts/canary.py", "--canary", "data/canary.jsonl",
                        "--reference", "ref/deepseek_t008.npz", "--out", str(out / "canary")])
    for cand in ("v4",):
        step(f"{{cand}}::{{model}}", [py, "scripts/zip_predict.py", "--zip-dir", f"zips/{{cand}}",
                                     "--model", model, "--rows", "data/rows.json",
                                     "--out", str(out / "preds" / f"{{cand}}__{{safe(model)}}.json")])
    shutil.rmtree(Path.home() / ".cache" / "huggingface" / "hub", ignore_errors=True)

report = {{"env": env, "timings": timings}}
(out / "kernel_report.json").write_text(json.dumps(report, indent=2))
print("REPORT", json.dumps(report), flush=True)
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT / "kaggle/aimo-t011-v4check")
    parser.add_argument("--slug", default="aimo-t011-v4check")
    parser.add_argument("--user", default="rajtaware10")
    arguments = parser.parse_args()
    text = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in TEXT}
    binary = {rel: base64.b64encode(path.read_bytes()).decode() for rel, path in BINARY.items()}
    arguments.out.mkdir(parents=True, exist_ok=True)
    (arguments.out / "run.py").write_text(RUNNER.format(models=MODELS, text=json.dumps(text),
                                                        binary=json.dumps(binary)))
    (arguments.out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{arguments.user}/{arguments.slug}", "title": arguments.slug, "code_file": "run.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_tpu": False, "enable_internet": True, "dataset_sources": [], "kernel_sources": [],
        "competition_sources": [], "model_sources": []}, indent=2))
    print(f"wrote {arguments.out}")


if __name__ == "__main__":
    main()
