"""T-022: generate the Kaggle kernel for Gate 1 (immediate-answer recall under a changed number).

    python scripts/make_kernel_t022.py --out <dir>
    kaggle kernels push -p <dir> --accelerator NvidiaTeslaT4

Same environment as T-019/T-021 (torch pin, transformers 5.13.0, fp16). Runs dump_recall.py on
the 173 pool problems for all four small models (smoke of 3 rows on the first), clearing the HF
cache between models. Writes T-022/recall__<model>.npz, logs/, kernel_report.json. No secrets.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEXT = ["src/selfperturb/__init__.py", "src/selfperturb/perturbations.py", "src/selfperturb/features.py",
        "scripts/dump_recall.py", "results/grok/T-014/problems.jsonl"]
MODELS = ["deepseek-ai/DeepSeek-R1-0528-Qwen3-8B", "Qwen/Qwen3.5-4B", "Skywork/Skywork-OR1-Math-7B",
          "allenai/Olmo-3-7B-Think"]
TORCH_PIN = "2.11.0+cu128"

RUNNER = '''\
"""Generated by scripts/make_kernel_t022.py -- edit the generator, not this file."""
import datetime, json, os, shutil, subprocess, sys, time
from pathlib import Path
T0 = time.time()
TEXT = json.loads(@@TEXT@@)
MODELS = json.loads(@@MODELS@@)
TORCH_PIN = @@TORCH_PIN@@
work, final = Path("/kaggle/working/repo"), Path("/kaggle/working/T-022")
for rel, content in TEXT.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(content, encoding="utf-8")
import torch as _t
if _t.__version__ != TORCH_PIN and not os.environ.get("T022_PINNED"):
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "torch==" + TORCH_PIN.split("+")[0],
                    "--index-url", "https://download.pytorch.org/whl/cu128"], check=False)
    os.environ["T022_PINNED"] = "1"
    os.execv(sys.executable, [sys.executable] + sys.argv)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "transformers==5.13.0", "accelerate==1.13.0"], check=False)
import torch, transformers
env = {"torch": torch.__version__, "transformers": transformers.__version__,
       "gpus": [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]}
(final / "logs").mkdir(parents=True, exist_ok=True)
timings, summaries = {}, {}

def report(done=False):
    (final / "kernel_report.json").write_text(json.dumps({"env": env, "wall_hours": round((time.time() - T0) / 3600, 3),
        "finished": done, "timings": timings, "summaries": summaries}, indent=2))

def step(key, cmd):
    t0 = time.time(); print("STEP", key, flush=True)
    with open(final / "logs" / (key + ".log"), "w") as handle:
        proc = subprocess.Popen(cmd, cwd=work, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                                env={**os.environ, "PYTHONPATH": str(work / "src")})
        for line in proc.stdout:
            print(line, end="", flush=True); handle.write(line)
            if line.startswith("SUMMARY "):
                summaries[key] = json.loads(line[8:])
        rc = proc.wait()
    timings[key] = {"seconds": round(time.time() - t0, 1), "returncode": rc}; report(); return rc

py, pool = sys.executable, "results/grok/T-014/problems.jsonl"
if step("smoke", [py, "scripts/dump_recall.py", "--model", MODELS[0], "--pool", pool, "--out", str(work / "smoke"), "--limit", "3"]) == 0:
    for m in MODELS:
        step(m.replace("/", "_"), [py, "scripts/dump_recall.py", "--model", m, "--pool", pool, "--out", str(final)])
        shutil.rmtree(Path.home() / ".cache" / "huggingface" / "hub", ignore_errors=True)
else:
    print("STOP smoke failed", flush=True)
report(done=True)
print("REPORT", (final / "kernel_report.json").read_text(), flush=True)
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--slug", default="aimo-t022-recall")
    parser.add_argument("--user", default="rajtaware10")
    args = parser.parse_args()
    text = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in TEXT}
    source = RUNNER.replace("@@TEXT@@", repr(json.dumps(text))).replace("@@MODELS@@", repr(json.dumps(MODELS))) \
                   .replace("@@TORCH_PIN@@", repr(TORCH_PIN))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "run.py").write_text(source)
    (args.out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{args.user}/{args.slug}", "title": args.slug, "code_file": "run.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_tpu": False,
        "enable_internet": True, "dataset_sources": [], "kernel_sources": [], "competition_sources": [],
        "model_sources": []}, indent=2))
    print("wrote", args.out)


if __name__ == "__main__":
    main()
