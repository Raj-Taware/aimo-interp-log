"""T-021: generate the self-contained Kaggle kernel (self-domain-rewrite white-box features).

    python scripts/make_kernel_t021.py --out <dir>
    kaggle kernels push -p <dir> --accelerator NvidiaTeslaT4

Derived from make_kernel_t019.py (Claude, 2026-10-29). Order: the same rule-3 canary (stop unless
max |diff| is exactly 0), then dump_selfdomain.py on 5 MATH rows (smoke; stop if any rewrite is empty,
contains <think> or \boxed), then all 137 rows. Writes T-021/selfdomain__<model>.npz, smoke/, logs/,
kernel_report.json. No secrets: every checkpoint is public.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
TEXT = ["src/selfperturb/__init__.py", "src/selfperturb/perturbations.py", "src/selfperturb/features.py",
        "scripts/dump_features.py", "scripts/canary.py", "scripts/dump_states.py", "scripts/dump_selfdomain.py"]
BINARY = {
    "ref/deepseek_t008.npz": ROOT / "results/grok/T-008/dumps/deepseek-ai_DeepSeek-R1-0528-Qwen3-8B.npz",
    "data/canary.jsonl": REPO / "collab/canary.jsonl",
}
URLS = {
    "data/math.parquet": "https://huggingface.co/api/datasets/aimo-interp/augmented-sample-math-agg/parquet/default/validation/0.parquet",
}
DEEPSEEK = "deepseek-ai/DeepSeek-R1-0528-Qwen3-8B"
OTHERS = ["Qwen/Qwen3.5-4B", "Skywork/Skywork-OR1-Math-7B", "allenai/Olmo-3-7B-Think"]
# (source key, parquet, expected rows) per model, DeepSeek first so the canary's download is reused.
PLAN = [(DEEPSEEK, [("math", "data/math.parquet", 137), ("trainv2", "data/trainv2.parquet", None),
                    ("pool", "data/pool_unlabelled.parquet", 173)])] + \
       [(m, [("trainv2", "data/trainv2.parquet", None), ("pool", "data/pool_unlabelled.parquet", 173)])
        for m in OTHERS]
TORCH_PIN = "2.11.0+cu128"

RUNNER = '''\
"""Generated by scripts/make_kernel_t021.py -- edit the generator, not this file."""
import base64, datetime, json, os, shutil, subprocess, sys, time
from pathlib import Path
KERNEL_T0 = time.time()

PLAN = json.loads(@@PLAN@@)
TORCH_PIN = @@TORCH_PIN@@
SHA = json.loads(@@SHA@@)
TEXT = json.loads(@@TEXT@@)
BINARY = json.loads(@@BINARY@@)

work = Path(os.environ.get("T021_WORK", "/kaggle/working/repo"))
final = Path(os.environ.get("T021_FINAL", "/kaggle/working/T-021"))
for rel, content in TEXT.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(content, encoding="utf-8")
for rel, blob in BINARY.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_bytes(base64.b64decode(blob))

if not os.environ.get("T021_DRYRUN"):
    import torch as _t
    if _t.__version__ != TORCH_PIN and not os.environ.get("T021_PINNED"):
        print("PIN torch", TORCH_PIN, "(image has", _t.__version__, ")", flush=True)
        subprocess.run([sys.executable, "-m", "pip", "install", "-q", "torch==" + TORCH_PIN.split("+")[0],
                        "--index-url", "https://download.pytorch.org/whl/cu128"], check=False)
        del _t
        os.environ["T021_PINNED"] = "1"
        os.execv(sys.executable, [sys.executable] + sys.argv)
    subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                    "transformers==5.13.0", "accelerate==1.13.0"], check=False)
import numpy as np
import torch, transformers, accelerate
env = {"torch": torch.__version__, "cuda": torch.version.cuda, "transformers": transformers.__version__,
       "accelerate": accelerate.__version__, "python": sys.version.split()[0], "dtype": "fp16",
       "gpus": [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]}
print("ENV", json.dumps(env), flush=True)

(final / "logs").mkdir(parents=True, exist_ok=True)
(final / "states").mkdir(parents=True, exist_ok=True)
scratch = work / "scratch"
timings, canary, runs = {}, {}, {}
report_path = final / "kernel_report.json"

def write_report(done=False):
    wall = time.time() - KERNEL_T0
    report_path.write_text(json.dumps({
        "env": env, "kernel_started_utc": datetime.datetime.fromtimestamp(KERNEL_T0, datetime.timezone.utc).isoformat(),
        "wall_seconds": round(wall, 1), "wall_hours": round(wall / 3600, 3), "finished": done,
        "parquet_sha256_prefix": SHA, "timings": timings, "canary": canary, "runs": runs}, indent=2))

def step(key, cmd):
    t0 = time.time()
    print("STEP", key, flush=True)
    log = final / "logs" / (key.replace("/", "_").replace("::", "__") + ".log")
    with open(log, "w") as handle:
        proc = subprocess.Popen(cmd, cwd=work, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in proc.stdout:
            print(line, end="", flush=True); handle.write(line)
        rc = proc.wait()
    timings[key] = {"seconds": round(time.time() - t0, 1), "returncode": rc}
    print("DONE", key, json.dumps(timings[key]), flush=True)
    write_report()
    return rc

def clear_cache():
    shutil.rmtree(Path.home() / ".cache" / "huggingface" / "hub", ignore_errors=True)
    print("DISK", shutil.disk_usage("/kaggle/working" if Path("/kaggle/working").exists() else "/"), flush=True)

py = sys.executable
safe = lambda m: m.replace("/", "_")

# 1. canary (rule 3): must reproduce T-008 exactly, else stop before any dump
rc = step("canary", [py, "scripts/canary.py", "--canary", "data/canary.jsonl",
                     "--reference", "ref/deepseek_t008.npz", "--out", str(final / "canary")])
metrics_path = final / "canary" / "metrics.json"
if rc == 0 and metrics_path.exists():
    m = json.loads(metrics_path.read_text())
    corr = [c for c in m["per_feature_corr"] if c == c]
    canary.update(max_abs_diff_all=m["max_abs_diff_all"], max_abs_diff_v3=m["max_abs_diff_v3"],
                  median_per_feature_corr=m["median_per_feature_corr"],
                  min_per_feature_corr=float(min(corr)) if corr else None,
                  worst_3=m["worst_3"], second_run_identical=m["second_run_identical"],
                  n_problems=m["n_problems"], seconds_per_problem_mean=m["seconds_per_problem_mean"])
canary["pass"] = bool(rc == 0 and canary.get("max_abs_diff_all") == 0.0)
print("CANARY", json.dumps(canary), flush=True)
write_report()

if not canary["pass"]:
    print("STOP canary: features differ from T-008 (or canary failed); no dumps run", flush=True)
else:
    model = PLAN[0][0]
    name = f"selfdomain__{safe(model)}.npz"
    rc = step("smoke", [py, "scripts/dump_selfdomain.py", "--model", model, "--source", "data/math.parquet",
                        "--out", str(final / "smoke"), "--limit", "5"])
    z = np.load(final / "smoke" / name, allow_pickle=True) if rc == 0 else None
    bad = [] if z is None else [r for r in z["rewrites"] if not r.strip() or "<think>" in r or "boxed{" in r]
    runs["smoke"] = {"returncode": rc, "rewrites": [] if z is None else list(map(str, z["rewrites"])), "bad": len(bad)}
    write_report()
    if rc != 0 or bad:
        print("STOP smoke: rewrites failed the check", flush=True)
    else:
        rc = step("full", [py, "scripts/dump_selfdomain.py", "--model", model, "--source", "data/math.parquet",
                           "--out", str(final)])
        z = np.load(final / name, allow_pickle=True) if rc == 0 else None
        runs["full"] = {"returncode": rc, "rows": 0 if z is None else int(len(z["labels"])), "expected_rows": 137,
                        "nonfinite": None if z is None else int((~np.isfinite(z["features"])).sum())}
        write_report()

write_report(done=True)
print("REPORT", report_path.read_text(), flush=True)
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path("/workspace/kaggle-aimo-t021/aimo-t021-selfdomain"))
    parser.add_argument("--slug", default="aimo-t021-selfdomain")
    parser.add_argument("--user", default="rajtaware10")
    arguments = parser.parse_args()
    text = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in TEXT}
    blobs = {rel: path.read_bytes() for rel, path in BINARY.items()}
    for rel, url in URLS.items():
        with urllib.request.urlopen(url) as response:
            blobs[rel] = response.read()
    sha = {rel: hashlib.sha256(data).hexdigest()[:16] for rel, data in blobs.items() if rel.endswith(".parquet")}
    binary = {rel: base64.b64encode(data).decode() for rel, data in blobs.items()}
    arguments.out.mkdir(parents=True, exist_ok=True)
    source = RUNNER
    for key, value in {"@@PLAN@@": repr(json.dumps(PLAN)), "@@TORCH_PIN@@": repr(TORCH_PIN),
                       "@@SHA@@": repr(json.dumps(sha)), "@@TEXT@@": repr(json.dumps(text)),
                       "@@BINARY@@": repr(json.dumps(binary))}.items():
        source = source.replace(key, value)
    (arguments.out / "run.py").write_text(source)
    (arguments.out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{arguments.user}/{arguments.slug}", "title": arguments.slug, "code_file": "run.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_tpu": False, "enable_internet": True, "dataset_sources": [], "kernel_sources": [],
        "competition_sources": [], "model_sources": []}, indent=2))
    print(f"wrote {arguments.out} (parquet sha256 prefixes: {sha})")


if __name__ == "__main__":
    main()
