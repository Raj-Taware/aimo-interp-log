"""T-018: generate the self-contained Kaggle kernel (v4 features on the 173 unlabelled pool problems -> v4b thresholds).

    python scripts/make_kernel_t018.py --out /workspace/kaggle-aimo-t018/aimo-t018-v4b
    kaggle kernels push -p /workspace/kaggle-aimo-t018/aimo-t018-v4b --accelerator NvidiaTeslaT4

Order (spec collab/tasks/T-018.md):
1. rule-3 canary: DeepSeek on collab/canary.jsonl vs results/grok/T-008/dumps/
   (scripts/canary.py). The kernel stops if max |diff| != 0 (spec: "stop if
   features differ"); the numbers are reported either way, nothing is "fixed".
2. ``dump_features.py --model <m> --source data/pool_unlabelled.parquet
   --out results/grok/T-018/features`` for the four small models (173 rows each;
   ``model_is_robust`` in that parquet is a dummy). HF cache cleared between models.
3. ``set_thresholds.py --features results/grok/T-018/features --artifacts
   results/artifacts-v4 --out results/grok/T-018/artifacts-v4b``.

Commands run from a copy of self-perturb/ at /kaggle/working/repo with the
spec's relative paths; results/grok/T-018 is mirrored to /kaggle/working/T-018
after every step, with kernel_report.json (env, wall time, canary, rows,
thresholds) and per-step logs. Torch is pinned to 2.11.0+cu128, the build under
which T-010/T-011/T-012/T-013 reproduced the T-008 canary exactly on T4 (same
choice as T-017). Embeds no secrets -- every checkpoint is public.
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
TEXT = ["src/selfperturb/__init__.py", "src/selfperturb/perturbations.py", "src/selfperturb/features.py",
        "src/selfperturb/geometry.py", "scripts/dump_features.py", "scripts/canary.py",
        "scripts/set_thresholds.py", "solutions/self-perturb/selfperturb_infer.py"]
BINARY = {
    "ref/deepseek_t008.npz": ROOT / "results/grok/T-008/dumps/deepseek-ai_DeepSeek-R1-0528-Qwen3-8B.npz",
    "data/canary.jsonl": REPO / "collab/canary.jsonl",
    "data/pool_unlabelled.parquet": ROOT / "data/pool_unlabelled.parquet",
    **{f"results/artifacts-v4/{p.name}": p for p in sorted((ROOT / "results/artifacts-v4").iterdir())},
}
DEEPSEEK = "deepseek-ai/DeepSeek-R1-0528-Qwen3-8B"
# DeepSeek first: the canary already downloaded it.
MODELS = [DEEPSEEK, "Qwen/Qwen3.5-4B", "Skywork/Skywork-OR1-Math-7B", "allenai/Olmo-3-7B-Think"]
TORCH_PIN = "2.11.0+cu128"

RUNNER = '''\
"""Generated by scripts/make_kernel_t018.py -- edit the generator, not this file."""
import base64, datetime, json, os, shutil, subprocess, sys, time
from pathlib import Path

KERNEL_T0 = float(os.environ.get("T018_T0", time.time()))
os.environ["T018_T0"] = repr(KERNEL_T0)
DEEPSEEK = {deepseek!r}
MODELS = {models!r}
TORCH_PIN = {torch_pin!r}
TEXT = json.loads({text!r})
BINARY = json.loads({binary!r})

work = Path(os.environ.get("T018_WORK", "/kaggle/working/repo"))
final = Path(os.environ.get("T018_FINAL", "/kaggle/working/T-018"))
for rel, content in TEXT.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(content, encoding="utf-8")
for rel, blob in BINARY.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_bytes(base64.b64decode(blob))

if not os.environ.get("T018_DRYRUN"):
    import torch as _t
    if _t.__version__ != TORCH_PIN and not os.environ.get("T018_PINNED"):
        print("PIN torch", TORCH_PIN, "(image has", _t.__version__, ")", flush=True)
        subprocess.run([sys.executable, "-m", "pip", "install", "-q", "torch==" + TORCH_PIN.split("+")[0],
                        "--index-url", "https://download.pytorch.org/whl/cu128"], check=False)
        del _t
        os.environ["T018_PINNED"] = "1"
        os.execv(sys.executable, [sys.executable] + sys.argv)
    subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                    "transformers==5.13.0", "accelerate==1.13.0"], check=False)
import numpy as np
import torch, transformers, accelerate
env = {{"torch": torch.__version__, "cuda": torch.version.cuda, "transformers": transformers.__version__,
        "accelerate": accelerate.__version__, "python": sys.version.split()[0], "dtype": "fp16",
        "gpus": [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]}}
print("ENV", json.dumps(env), flush=True)

res = work / "results/grok/T-018"          # spec-relative output dir
(res / "logs").mkdir(parents=True, exist_ok=True)
timings, canary, rows = {{}}, {{}}, {{}}
thresholds = None
report_path = res / "kernel_report.json"

def write_report(done=False):
    wall = time.time() - KERNEL_T0
    report = {{"env": env, "kernel_started_utc": datetime.datetime.fromtimestamp(KERNEL_T0, datetime.timezone.utc).isoformat(),
              "wall_seconds": round(wall, 1), "wall_hours": round(wall / 3600, 3), "finished": done,
              "timings": timings, "canary": canary, "rows_per_model": rows, "thresholds": thresholds}}
    report_path.write_text(json.dumps(report, indent=2))
    shutil.copytree(res, final, dirs_exist_ok=True)
    return report

def step(key, cmd):
    t0 = time.time()
    print("STEP", key, flush=True)
    log = res / "logs" / (key.replace("/", "_").replace("::", "__") + ".log")
    with open(log, "w") as handle:
        proc = subprocess.Popen(cmd, cwd=work, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in proc.stdout:
            print(line, end="", flush=True); handle.write(line)
        rc = proc.wait()
    timings[key] = {{"seconds": round(time.time() - t0, 1), "returncode": rc}}
    print("DONE", key, json.dumps(timings[key]), flush=True)
    write_report()
    return rc

def clear_cache():
    shutil.rmtree(Path.home() / ".cache" / "huggingface" / "hub", ignore_errors=True)
    print("DISK", shutil.disk_usage("/kaggle/working" if Path("/kaggle/working").exists() else "/"), flush=True)

py = sys.executable
safe = lambda m: m.replace("/", "_")

# 1. canary (rule 3)
rc = step("canary", [py, "scripts/canary.py", "--canary", "data/canary.jsonl",
                     "--reference", "ref/deepseek_t008.npz", "--out", "results/grok/T-018/canary"])
metrics_path = res / "canary" / "metrics.json"
if rc == 0 and metrics_path.exists():
    m = json.loads(metrics_path.read_text())
    corr = [c for c in m["per_feature_corr"] if c == c]
    canary.update(max_abs_diff_all=m["max_abs_diff_all"], max_abs_diff_v3=m["max_abs_diff_v3"],
                  median_per_feature_corr=m["median_per_feature_corr"],
                  min_per_feature_corr=float(min(corr)) if corr else None,
                  worst_3=m["worst_3"], second_run_identical=m["second_run_identical"],
                  n_problems=m["n_problems"], seconds_per_problem_mean=m["seconds_per_problem_mean"])
canary["pass"] = bool(rc == 0 and canary.get("max_abs_diff_all") == 0.0)
print("CANARY", json.dumps(canary), flush=True)
write_report()

if not canary["pass"]:
    print("STOP canary: features differ from T-008 (or canary failed); no dumps run", flush=True)
else:
    # 2. pool dumps, spec command verbatim
    for model in MODELS:
        step(f"dump::{{model}}", [py, "scripts/dump_features.py", "--model", model,
                                  "--source", "data/pool_unlabelled.parquet", "--out", "results/grok/T-018/features"])
        clear_cache()
        path = res / "features" / f"{{safe(model)}}.npz"
        if path.exists():
            z = np.load(path, allow_pickle=True)
            rows[model] = {{"rows": int(len(z["features"])), "n_features": int(z["features"].shape[1]),
                           "nan_cells": int(np.isnan(z["features"]).sum())}}
        else:
            rows[model] = {{"rows": 0}}
        print("ROWS", model, json.dumps(rows[model]), flush=True)
        write_report()
    # 3. thresholds
    if all(r.get("rows") == 173 for r in rows.values()) and len(rows) == len(MODELS):
        rc = step("set_thresholds", [py, "scripts/set_thresholds.py", "--features", "results/grok/T-018/features",
                                     "--artifacts", "results/artifacts-v4", "--out", "results/grok/T-018/artifacts-v4b"])
        tj = res / "artifacts-v4b" / "thresholds.json"
        if tj.exists():
            thresholds = json.loads(tj.read_text())
            shutil.copy(tj, res / "thresholds.json")
    else:
        print("SKIP set_thresholds: not every model has 173 rows", json.dumps(rows), flush=True)

report = write_report(done=True)
print("REPORT", json.dumps(report), flush=True)
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path("/workspace/kaggle-aimo-t018/aimo-t018-v4b"))
    parser.add_argument("--slug", default="aimo-t018-v4b")
    parser.add_argument("--user", default="rajtaware10")
    arguments = parser.parse_args()
    text = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in TEXT}
    binary = {rel: base64.b64encode(Path(path).read_bytes()).decode() for rel, path in BINARY.items()}
    arguments.out.mkdir(parents=True, exist_ok=True)
    (arguments.out / "run.py").write_text(RUNNER.format(deepseek=DEEPSEEK, models=MODELS, torch_pin=TORCH_PIN,
                                                        text=json.dumps(text), binary=json.dumps(binary)))
    (arguments.out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{arguments.user}/{arguments.slug}", "title": arguments.slug, "code_file": "run.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_tpu": False, "enable_internet": True, "dataset_sources": [], "kernel_sources": [],
        "competition_sources": [], "model_sources": []}, indent=2))
    print(f"wrote {arguments.out}: {sorted(text)} + {sorted(binary)}")


if __name__ == "__main__":
    main()
