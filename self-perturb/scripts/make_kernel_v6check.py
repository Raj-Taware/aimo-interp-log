"""Kaggle check of the v6 bundle: run the real are_robust path for every model on the
train-main-v2 problems and compare each standardized difficulty with the offline value
from the T-019 states (same prompt, fp16). Writes v6check/report.json.

    python scripts/make_kernel_v6check.py --bundle <solution-v6-...zip> --out <dir>
    kaggle kernels push -p <dir> --accelerator NvidiaTeslaT4
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
STATES = ROOT / "results/grok/T-019/states"

RUNNER = '''"""Generated by scripts/make_kernel_v6check.py."""
import base64, io, json, os, subprocess, sys, time, zipfile
from pathlib import Path
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "transformers==5.13.0", "accelerate==1.13.0"], check=False)
BUNDLE = base64.b64decode(@@BUNDLE@@)
EXPECTED = json.loads(@@EXPECTED@@)
work = Path("/kaggle/working/bundle"); work.mkdir(parents=True, exist_ok=True)
zipfile.ZipFile(io.BytesIO(BUNDLE)).extractall(work)
sys.path.insert(0, str(work))
import numpy as np, torch, transformers
import difficulty_infer as di
from selfperturb.features import load_model
out = Path("/kaggle/working/v6check"); out.mkdir(exist_ok=True)
report = {"env": {"torch": torch.__version__, "transformers": transformers.__version__,
                  "gpus": [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]}, "models": {}}
for model_id, rows in EXPECTED.items():
    t0 = time.time()
    preds = di.predict_robustness(model_id, [r["problem"] for r in rows])
    call = time.time() - t0
    art = np.load(work / "probe_artifacts" / (di._safe_id(model_id) + ".npz"), allow_pickle=True)
    tok, model = load_model(model_id)
    got = [di.difficulty(tok, model, art, r["problem"]) for r in rows]
    del model; torch.cuda.empty_cache()
    exp = [r["z"] for r in rows]
    report["models"][model_id] = {"n": len(rows), "call_seconds": round(call, 1),
        "max_abs_diff_z": float(np.max(np.abs(np.array(got) - np.array(exp)))),
        "preds_match_offline": [bool(p) == (e < float(art["cut"])) for p, e in zip(preds, exp)].count(True),
        "types_ok": all(type(p) is bool for p in preds), "preds": preds}
    print(model_id, json.dumps(report["models"][model_id]), flush=True)
    (out / "report.json").write_text(json.dumps(report, indent=2))
    subprocess.run(["rm", "-rf", str(Path.home() / ".cache/huggingface/hub")])
print("REPORT", json.dumps(report), flush=True)
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bundle", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--slug", default="aimo-v6-check")
    parser.add_argument("--user", default="rajtaware10")
    args = parser.parse_args()
    import zipfile, io
    z = zipfile.ZipFile(args.bundle)
    expected = {}
    for name in z.namelist():
        if not name.startswith("probe_artifacts/"):
            continue
        art = np.load(io.BytesIO(z.read(name)), allow_pickle=True)
        safe = Path(name).stem
        tr = np.load(STATES / f"trainv2__{safe}__states.npz", allow_pickle=True)
        layer_index = list(tr["layers"]).index(int(art["layer"]))
        X = tr[str(art["pooling"])][:, layer_index].astype(np.float32)
        raw = ((X - art["mean"]) / art["scale"]) @ art["coef"] + float(art["intercept"])
        zs = (raw - float(art["pool_mu"])) / float(art["pool_sd"])
        expected[str(art["model_id"])] = [{"problem": str(p), "z": float(v)} for p, v in zip(tr["problems"], zs)]
    src = RUNNER.replace("@@BUNDLE@@", repr(base64.b64encode(args.bundle.read_bytes()).decode())) \
                .replace("@@EXPECTED@@", repr(json.dumps(expected)))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "run.py").write_text(src)
    (args.out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{args.user}/{args.slug}", "title": args.slug, "code_file": "run.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_tpu": False,
        "enable_internet": True, "dataset_sources": [], "kernel_sources": [], "competition_sources": [],
        "model_sources": []}, indent=2))
    print("wrote", args.out, {k: len(v) for k, v in expected.items()})


if __name__ == "__main__":
    main()
