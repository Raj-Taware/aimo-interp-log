"""T-016: generate a self-contained Kaggle T4x2 kernel that runs one phase script.

    python scripts/label_gen/make_kernel_t016.py --phase step0 --slug aimo-t016-step0 --out /workspace/kaggle-aimo-t016/step0
    kaggle kernels push -p /workspace/kaggle-aimo-t016/step0 --accelerator NvidiaTeslaT4

Embeds the label_gen code + selfperturb src (no secrets). The phase body is
scripts/label_gen/t016_phases.py <phase>; it runs inside /kaggle/working/repo/self-perturb
and writes results to /kaggle/working/T-016.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent  # self-perturb/
FILES = ["src/selfperturb/__init__.py", "src/selfperturb/perturbations.py", "src/selfperturb/features.py",
         *[f"scripts/label_gen/{n}" for n in ("common.py", "stage0_gold.py", "stage1_solve.py",
           "stage3_solve_variants.py", "claude_variants_gate.py", "gate_check.py", "t016_phases.py")]]

RUNNER = '''\
"""Generated by scripts/label_gen/make_kernel_t016.py -- edit the generator, not this file."""
import json, subprocess, sys
from pathlib import Path
TEXT = json.loads({text!r})
work = Path("/kaggle/working/repo/self-perturb")
for rel, content in TEXT.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(content, encoding="utf-8")
sys.exit(subprocess.run([sys.executable, "scripts/label_gen/t016_phases.py", {phase!r}], cwd=work).returncode)
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", required=True)
    ap.add_argument("--slug", required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--user", default="rajtaware10")
    a = ap.parse_args()
    text = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in FILES}
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "run.py").write_text(RUNNER.format(text=json.dumps(text), phase=a.phase))
    (a.out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{a.user}/{a.slug}", "title": a.slug, "code_file": "run.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_tpu": False,
        "enable_internet": True, "dataset_sources": [], "kernel_sources": [], "competition_sources": [],
        "model_sources": []}, indent=2))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
