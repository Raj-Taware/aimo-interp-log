"""T-020: generate a self-contained Kaggle T4x2 kernel for the self-made MATH labels.

    # Phase 1 (gate, 40 problems):
    python scripts/label_gen/make_kernel_t020.py --phase gate --slug aimo-t020-gate --out /workspace/kaggle-aimo-t020/gate
    # Phase 2 (two kernels, strided halves of problems_new.jsonl):
    python scripts/label_gen/make_kernel_t020.py --phase new --half 0 --halves 2 --slug aimo-t020-new0 --out ...
    python scripts/label_gen/make_kernel_t020.py --phase new --half 1 --halves 2 --slug aimo-t020-new1 --out ...
    # resume after an interrupted kernel: --resume-from rajtaware10/<old-slug> (its outputs are mounted at /kaggle/input)
    kaggle kernels push -p <out> --accelerator NvidiaTeslaT4

Embeds the label_gen code, selfperturb src and the committed T-020 inputs (no secrets).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent  # self-perturb/
FILES = ["src/selfperturb/__init__.py", "src/selfperturb/perturbations.py", "src/selfperturb/features.py",
         *[f"scripts/label_gen/{n}" for n in ("common.py", "stage1_solve.py", "stage3_solve_variants.py",
                                              "math_gate.py", "t020_phases.py")],
         *[f"results/grok/T-020/{n}" for n in ("problems.jsonl", "problems_gate.jsonl", "problems_new.jsonl",
                                               "stage2_variants.jsonl")]]

RUNNER = '''\
"""Generated by scripts/label_gen/make_kernel_t020.py -- edit the generator, not this file."""
import json, subprocess, sys
from pathlib import Path
TEXT = json.loads({text!r})
work = Path("/kaggle/working/repo/self-perturb")
for rel, content in TEXT.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(content, encoding="utf-8")
sys.exit(subprocess.run([sys.executable, "scripts/label_gen/t020_phases.py", *{args!r}], cwd=work).returncode)
'''


def build(phase: str, slug: str, out: Path, half: int = 0, halves: int = 1, user: str = "rajtaware10",
          resume_from: str | None = None, chunk_size: int = 96) -> Path:
    if phase == "gate" and halves != 1:
        raise SystemExit("--halves applies to --phase new only")
    if not 0 <= half < halves:
        raise SystemExit("need 0 <= half < halves")
    text = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in FILES}
    args = ["--phase", phase, "--half", str(half), "--halves", str(halves), "--chunk-size", str(chunk_size)]
    out.mkdir(parents=True, exist_ok=True)
    (out / "run.py").write_text(RUNNER.format(text=json.dumps(text), args=args))
    (out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{user}/{slug}", "title": slug, "code_file": "run.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_tpu": False,
        "enable_internet": True, "dataset_sources": [], "competition_sources": [], "model_sources": [],
        "kernel_sources": [resume_from] if resume_from else []}, indent=2))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--phase", choices=("gate", "new"), required=True)
    ap.add_argument("--half", type=int, default=0)
    ap.add_argument("--halves", type=int, default=1)
    ap.add_argument("--slug", required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--user", default="rajtaware10")
    ap.add_argument("--resume-from", default=None)
    ap.add_argument("--chunk-size", type=int, default=96)
    a = ap.parse_args()
    print("wrote", build(a.phase, a.slug, a.out, a.half, a.halves, a.user, a.resume_from, a.chunk_size))


if __name__ == "__main__":
    main()
