"""T-014: generate the self-contained Kaggle kernel for the label_gen dry run.

    python scripts/label_gen/make_kernel_t014.py --out /workspace/kaggle-aimo-t014/aimo-t014-labelgen-dryrun
    kaggle kernels push -p /workspace/kaggle-aimo-t014/aimo-t014-labelgen-dryrun --accelerator NvidiaTeslaT4

Kaggle T4x2, transformers generate (no vLLM), Skywork-OR1-Math-7B as both the
solver and the stand-in stage-2 writer; 3 AIME + 3 AMC problems, 2 samples,
4096 new tokens. Runs scripts/label_gen/dryrun_t014.py (stage 1 -> 2 -> 3, each
killed once mid-run, resumed, then re-run as a no-op). Embeds no secrets.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent  # self-perturb/
TEXT = ["src/selfperturb/__init__.py", "src/selfperturb/perturbations.py", "src/selfperturb/features.py",
        "scripts/label_gen/common.py", "scripts/label_gen/stage1_solve.py",
        "scripts/label_gen/stage2_variants.py", "scripts/label_gen/stage3_solve_variants.py",
        "scripts/label_gen/dryrun_t014.py", "results/grok/T-014/problems.jsonl"]
MODEL = "Skywork/Skywork-OR1-Math-7B"
PROBLEM_IDS = ["aime-0", "aime-1", "aime-2", "amc-0", "amc-1", "amc-2"]

RUNNER = '''\
"""Generated by scripts/label_gen/make_kernel_t014.py -- edit the generator, not this file."""
import json, subprocess, sys, time
from pathlib import Path

TEXT = json.loads({text!r})
work = Path("/kaggle/working/repo")
for rel, content in TEXT.items():
    p = work / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(content, encoding="utf-8")

subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                "transformers==5.13.0", "accelerate==1.13.0"], check=False)
import torch, transformers, accelerate
env = {{"torch": torch.__version__, "cuda": torch.version.cuda, "transformers": transformers.__version__,
        "accelerate": accelerate.__version__,
        "gpus": [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]}}
print("ENV", json.dumps(env), flush=True)
out = Path("/kaggle/working/T-014")
out.mkdir(parents=True, exist_ok=True)
(out / "env.json").write_text(json.dumps(env, indent=2))
pids = sum((["--problem-id", x] for x in {pids!r}), [])
t0 = time.time()
cmd = [sys.executable, "scripts/label_gen/dryrun_t014.py", "--problems", "results/grok/T-014/problems.jsonl",
       *pids, "--model", {model!r}, "--writer", {model!r}, "--out", str(out / "run"),
       "--samples", "2", "--variant-samples", "2", "--max-new-tokens", "4096",
       "--writer-max-new-tokens", "4096", "--batch1", "6", "--batch-cap", "10", "--backend", "hf"]
rc = subprocess.run(cmd, cwd=work / "self-perturb" if (work / "self-perturb").exists() else work).returncode
(out / "kernel_done.json").write_text(json.dumps({{"returncode": rc, "seconds": round(time.time() - t0, 1),
                                                  "env": env}}, indent=2))
print("KERNEL DONE rc", rc, "seconds", round(time.time() - t0, 1), flush=True)
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path("/workspace/kaggle-aimo-t014/aimo-t014-labelgen-dryrun"))
    parser.add_argument("--slug", default="aimo-t014-labelgen-dryrun")
    parser.add_argument("--user", default="rajtaware10")
    args = parser.parse_args()
    text = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in TEXT}
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "run.py").write_text(RUNNER.format(text=json.dumps(text), pids=PROBLEM_IDS, model=MODEL))
    (args.out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{args.user}/{args.slug}", "title": args.slug, "code_file": "run.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_tpu": False, "enable_internet": True, "dataset_sources": [], "kernel_sources": [],
        "competition_sources": [], "model_sources": []}, indent=2))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
